# Independent check of explicit sets: every row, column, diagonal and anti-diagonal of (Z/kZ)^2
# (all 8 directions, all base points) meets A in at least 2 points, and |A| <= 2k+2.
import itertools, sys
EX = {
6: """##....
##....
..###.
#....#
.##...
...###""",
9: """.#......#
...#..#..
#..#..#..
..#....#.
..#..#...
....#..#.
#.....#..
.#.##....
.....#..#""",
12: """....#....#..
...#.#......
.....#.#....
..#.....#...
.#.........#
......##..#.
##..........
......#.#...
..#.#.#.....
#....#......
...#......#.
.........#.#""",
15: """...#....#......
...#.......#...
.#.......#.....
.........#....#
..#..#.........
..........#.#..
..#.#.....#....
......#......#.
.....#..#......
#............#.
...........##..
#...#..........
..#...##.......
.#.....#.......
...........#..#""",
}
for k,txt in EX.items():
    rows=txt.split("\n")
    A={(x,y) for y,r in enumerate(rows) for x,ch in enumerate(r) if ch=='#'}
    ok = len(A) <= 2*k+2
    m = 99
    for p in itertools.product(range(k),repeat=2):
        for d in itertools.product((-1,0,1),repeat=2):
            if d==(0,0): continue
            L={((p[0]+t*d[0])%k,(p[1]+t*d[1])%k) for t in range(k)}
            assert len(L)==k
            m=min(m,len(L&A))
    print(k, 'size',len(A),'<=',2*k+2, 'min line count', m, 'OK' if ok and m>=2 else 'FAIL')
    print('  lean:', '{' + ', '.join(f'({x}, {y})' for (x,y) in sorted(A)) + '}')
