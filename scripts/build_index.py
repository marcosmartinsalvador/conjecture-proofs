#!/usr/bin/env python3
"""Rebuild the results tables on the front page from conjectures/<folder>/result.json.

    python3 scripts/build_index.py           rewrite README.md
    python3 scripts/build_index.py --check   exit 1 if README.md is out of date,
                                             or if a result folder is incomplete

Each result folder must hold README.md, result.json, Statement.lean and Proof.lean.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BEGIN = '<!-- BEGIN RESULTS (generated by scripts/build_index.py; edit result.json, not this table) -->'
END = '<!-- END RESULTS -->'
REQUIRED = ('README.md', 'result.json', 'Statement.lean', 'Proof.lean')
KINDS = ('full', 'partial', 'known')
FIELDS = ('slug', 'title', 'kind', 'outcome', 'summary', 'source', 'url', 'label', 'checked', 'rank', 'new')


def load():
    base = os.path.join(ROOT, 'conjectures')
    results, problems = [], []
    for slug in sorted(os.listdir(base)):
        d = os.path.join(base, slug)
        if not os.path.isdir(d):
            continue
        for f in REQUIRED:
            if not os.path.isfile(os.path.join(d, f)):
                problems.append(f'{slug}: missing {f}')
        p = os.path.join(d, 'result.json')
        if not os.path.isfile(p):
            continue
        r = json.load(open(p, encoding='utf-8'))
        for f in FIELDS:
            if f not in r:
                problems.append(f'{slug}: result.json has no "{f}"')
        if r.get('slug') != slug:
            problems.append(f'{slug}: result.json says slug "{r.get("slug")}"')
        if r.get('kind') not in KINDS:
            problems.append(f'{slug}: kind must be one of {KINDS}')
        if r.get('kind') == 'known' and not r.get('first_by'):
            problems.append(f'{slug}: a known result needs "first_by"')
        results.append(r)
    results.sort(key=lambda r: (r.get('rank', 10**6), r.get('slug', '')))
    return results, problems


def cell(text):
    return str(text).replace('|', '\\|').replace('\n', ' ')


def cap(text):
    return text[:1].upper() + text[1:]


def link(r):
    return f"[{cell(r['title'])}](conjectures/{r['slug']}/)"


def source_link(r):
    short = r['source'].split(', "')[0] if ', "' in r['source'] else r['source'].split(',')[0]
    return f"[{cell(short)}]({r['url']})"


def tables(results):
    full = [r for r in results if r['kind'] == 'full']
    part = [r for r in results if r['kind'] == 'partial']
    known = [r for r in results if r['kind'] == 'known']
    out = [BEGIN, '']
    out.append(f'**{len(full)} full resolutions, {len(part)} partial '
               f'result{"" if len(part) == 1 else "s"}, {len(known)} known results.** '
               'All are checked in Lean. They are listed in rough order of significance.')
    out.append('')
    out.append('### Full resolutions')
    out.append('')
    out.append('Each of these settles a conjecture as its source states it.')
    out.append('')
    out.append('| # | Result | Outcome | Source | Checked | New? |')
    out.append('|---|---|---|---|---|---|')
    for i, r in enumerate(full, 1):
        out.append(f"| {i} | {link(r)}<br>{cell(r['summary'])} | {cell(r['outcome'])} | "
                   f"{source_link(r)} | {r['checked']} | {cell(cap(r['new']))} |")
    out.append('')
    out.append('### Partial results')
    out.append('')
    out.append('Each of these settles part of a question. The question itself is still open.')
    out.append('')
    if part:
        out.append('| Result | What is proved | Source | Checked | New? |')
        out.append('|---|---|---|---|---|')
        for r in part:
            out.append(f"| {link(r)} | {cell(r['summary'])} | {source_link(r)} | "
                       f"{r['checked']} | {cell(cap(r['new']))} |")
    else:
        out.append('None yet.')
    out.append('')
    out.append('### Known results')
    out.append('')
    out.append('These were proved and machine-checked here, but someone else had them first. '
               'They are not claimed as new.')
    out.append('')
    if known:
        out.append('| Result | Outcome | Source | Who had it first |')
        out.append('|---|---|---|---|')
        for r in known:
            out.append(f"| {link(r)}<br>{cell(r['summary'])} | {cell(r['outcome'])} | "
                       f"{source_link(r)} | {cell(r['first_by'])} |")
    else:
        out.append('None.')
    out.append('')
    out.append(END)
    return '\n'.join(out)


def main():
    check = '--check' in sys.argv[1:]
    results, problems = load()
    path = os.path.join(ROOT, 'README.md')
    text = open(path, encoding='utf-8').read()
    if BEGIN not in text or END not in text:
        problems.append('README.md has lost its BEGIN RESULTS / END RESULTS markers')
        new = text
    else:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        new = head + tables(results) + tail
    if problems:
        print('\n'.join(problems))
        return 1
    if check:
        if new != text:
            print('README.md is out of date: run  python3 scripts/build_index.py')
            return 1
        print(f'README.md is up to date ({len(results)} results)')
        return 0
    open(path, 'w', encoding='utf-8').write(new)
    print(f'README.md rebuilt ({len(results)} results)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
